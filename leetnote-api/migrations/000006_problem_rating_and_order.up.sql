-- =============================================================
-- 000006_problem_rating_and_order · 难度分 + 题单顺序
-- =============================================================

-- ---------------------------------------------------------------
-- 1. 难度分（rating）
--
-- LeetCode 官方只给 Easy/Medium/Hard 三档，粒度太粗 ——
-- 同为 Medium，有的 1400 分有的 2600 分，难度天差地别。
--
-- 难度分由社区项目 zerotrac/leetcode_problem_rating 根据竞赛数据
-- 统计得出（用通过率与参赛者表现反推），是目前公认最准的一档。
-- 灵神题单里的「难度分 ≤ 1700」说的就是这个值。
--
-- 用 REAL 而不是 INTEGER：原始数据带小数（如 3124.5016688063），
-- 排序展示时保留小数更有区分度。
-- ---------------------------------------------------------------
ALTER TABLE problems ADD COLUMN rating REAL;

-- 按难度分筛选/排序都要用
CREATE INDEX idx_problems_rating ON problems (rating);

-- ---------------------------------------------------------------
-- 2. 题单顺序
--
-- 题单本身是【有序】的（从易到难），这个顺序本身携带信息 ——
-- 按题号排序会把这个顺序打乱，变成随机难度。
--
-- 0 表示「不属于任何题单」（手工录入的题目）。
-- ---------------------------------------------------------------
ALTER TABLE problems ADD COLUMN sort_order INTEGER NOT NULL DEFAULT 0;

CREATE INDEX idx_problems_sort_order ON problems (sort_order);

-- ---------------------------------------------------------------
-- 3. 专题顺序
--
-- 让「相向双指针 → 滑动窗口 → 二分查找 → …」这个题单里的专题顺序
-- 能被还原，而不是按 ID 或拼音排。
-- ---------------------------------------------------------------
ALTER TABLE tags ADD COLUMN sort_order INTEGER NOT NULL DEFAULT 0;
